import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { FUNCTION_DATA_PUBLIC_DIR } from '../../src/haybarn-functions/data/function-data-paths.mjs';

const snapshotDirectory = resolve('src/haybarn-functions/data/snapshots');
const output = resolve('src/haybarn-functions/data/snapshots.generated.ts');
const files = (await readdir(snapshotDirectory))
  .filter(file => file.endsWith('.json'))
  .sort();

if (!files.length) throw new Error(`No snapshot JSON files found in ${snapshotDirectory}`);

const imports = files.map((file, index) => `import snapshot${index} from './snapshots/${file}';`);
const source = [
  '// Generated by scripts/haybarn-functions/generate-snapshot-module.mjs.',
  '// Commit this file so Astro, Wrangler, tests, and editors load the same snapshots.',
  ...imports,
  '',
  `export const snapshotModules = [${files.map((_, index) => `snapshot${index}`).join(', ')}];`,
  '',
  '/** The snapshots are imported above, so there is nothing to fetch. See snapshots.edge.generated.ts. */',
  'export async function loadSnapshotData(_fetchJson: (path: string) => Promise<unknown>): Promise<void> {}',
  '',
].join('\n');

await writeFile(output, source);
console.log(`[snapshots] Generated ${files.length} imports in ${output}`);

// The Pages Functions bundle gets metadata only (package.json "imports",
// workerd condition) and fetches each snapshot's functions from a minified
// static copy. See src/haybarn-functions/data/function-data-paths.mjs.
const staticDirectory = resolve(FUNCTION_DATA_PUBLIC_DIR, 'snapshots');
await rm(staticDirectory, { recursive: true, force: true });
await mkdir(staticDirectory, { recursive: true });
const metadata = [];
for (const file of files) {
  const { functions, ...rest } = JSON.parse(await readFile(resolve(snapshotDirectory, file), 'utf8'));
  if (!Array.isArray(functions)) throw new Error(`${file} has no functions array`);
  metadata.push(rest);
  await writeFile(resolve(staticDirectory, `${rest.id}.json`), JSON.stringify({ id: rest.id, functions }));
}
const edgeSource = [
  '// Generated by scripts/haybarn-functions/generate-snapshot-module.mjs.',
  '// The Pages Functions build of snapshots.generated.ts (package.json "imports",',
  '// workerd condition): metadata only, with each functions array fetched from a',
  '// static copy by loadSnapshotData().',
  "import { edgeSnapshotModules } from '../lib/edge-snapshots';",
  '',
  `export const { snapshotModules, loadSnapshotData } = edgeSnapshotModules(${JSON.stringify(metadata, null, 2)});`,
  '',
].join('\n');
await writeFile(resolve('src/haybarn-functions/data/snapshots.edge.generated.ts'), edgeSource);
console.log(`[snapshots] Generated edge metadata and ${files.length} static copies in ${staticDirectory}`);

const bindingDirectory = resolve('src/haybarn-functions/data/bindings');
const bindingOutput = resolve('src/haybarn-functions/data/bindings.generated.ts');
const bindingFiles = (await readdir(bindingDirectory))
  .filter(file => file.endsWith('.json'))
  .sort();
const bindingSource = [
  '// Generated by scripts/haybarn-functions/generate-snapshot-module.mjs.',
  '// Commit this file so Astro, Wrangler, tests, and editors load the same captures.',
  ...bindingFiles.map((file, index) => `import binding${index} from './bindings/${file}';`),
  '',
  `export const bindingModules = [${bindingFiles.map((_, index) => `binding${index}`).join(', ')}];`,
  '',
].join('\n');
await writeFile(bindingOutput, bindingSource);
console.log(`[snapshots] Generated ${bindingFiles.length} imports in ${bindingOutput}`);
